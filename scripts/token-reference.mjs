/**
 * Render the token reference document.
 *
 * The document is a deterministic Markdown file: palette primitives, accent
 * roles, semantic tokens split into their groups, component tokens grouped by
 * component, and the internal tokens. The content comes from
 * `token-sections.mjs`; this module only lays it out, so the same sections can be
 * rendered from a fixture or from the compiled framework.
 *
 * @module token-reference
 */

import { countTokenRows, readTokenSections } from './token-sections.mjs';

const TOKEN_COLUMNS = ['Token', 'Light', 'Dark', 'Controlled by'];
const INTERNAL_COLUMNS = ['Token', 'Light', 'Dark', 'Note'];
const INTERNAL_NOTE = 'internal';
const INTRODUCTION = [
    '# Token reference',
    '',
    'Generated by `npm run tokens` from `src/sass`. Do not edit by hand.',
    '',
    '`Light` and `Dark` are the resolved values for each theme scope. Tokens starting with `--_r-` are internal to the framework and are not part of the public API.',
];

/**
 * Render the token reference for one resolved token snapshot.
 *
 * @param {{light: Map<string, string>, dark: Map<string, string>, sources: {settingsPairs: Map<string, string>, themeTokens: Set<string>}}} input
 * Resolved token maps and the wiring read from `_css-variable.scss`.
 * @returns {{markdown: string, counts: {total: number, public: number, internal: number}}} Document text and token totals.
 * @throws {Error} When a palette token does not match a slot, an accent role matches several slots, or a token cannot be classified.
 */
export function renderTokenReference({ light, dark, sources }) {
    const sections = readTokenSections({ light, dark, sources });
    const total = countTokenRows(sections);

    return {
        markdown: renderMarkdown(sections),
        counts: { total, public: total - sections.internal.length, internal: sections.internal.length },
    };
}

/**
 * Lay the sections out as Markdown.
 *
 * @param {import('./token-sections.mjs').Sections} sections Sections in documented order.
 * @returns {string} Markdown document ending in a newline.
 */
function renderMarkdown(sections) {
    const lines = [
        ...INTRODUCTION,
        '',
        '## Palette primitives',
        '',
        renderTable(TOKEN_COLUMNS, sections.palette.map(toTokenCells)),
        '',
        '## Accent roles',
        '',
        renderTable(TOKEN_COLUMNS, sections.accentRoles.map(toTokenCells)),
        '',
        '## Semantic tokens',
    ];

    appendGroups(lines, sections.semantic);
    lines.push('', '## Component tokens');
    appendGroups(lines, sections.components);
    lines.push('', '## Internal tokens', '', renderTable(INTERNAL_COLUMNS, sections.internal.map(toInternalCells)));

    return `${lines.join('\n')}\n`;
}

/**
 * Append one level-three heading and table per group.
 *
 * @param {string[]} lines Document lines to extend.
 * @param {import('./token-sections.mjs').TokenGroup[]} groups Groups to append.
 * @returns {void}
 */
function appendGroups(lines, groups) {
    for (const { title, rows } of groups) {
        lines.push('', `### ${title}`, '', renderTable(TOKEN_COLUMNS, rows.map(toTokenCells)));
    }
}

/**
 * Render one table from column headers and preformatted cell rows.
 *
 * @param {string[]} headers Column headers.
 * @param {string[][]} rows Cell values per row.
 * @returns {string} Markdown table.
 */
function renderTable(headers, rows) {
    const lines = [
        `| ${headers.join(' | ')} |`,
        `| ${headers.map(() => '---').join(' | ')} |`,
        ...rows.map((cells) => `| ${cells.join(' | ')} |`),
    ];

    return lines.join('\n');
}

/**
 * Format a public token row.
 *
 * @param {import('./token-sections.mjs').TokenRow} row Row to format.
 * @returns {string[]} Cell values.
 */
function toTokenCells(row) {
    return [codeSpan(row.token), formatValue(row.light), formatValue(row.dark), formatControl(row.control)];
}

/**
 * Format an internal token row.
 *
 * @param {import('./token-sections.mjs').TokenRow} row Row to format.
 * @returns {string[]} Cell values.
 */
function toInternalCells(row) {
    return [codeSpan(row.token), formatValue(row.light), formatValue(row.dark), INTERNAL_NOTE];
}

/**
 * Format a control descriptor as one table cell.
 *
 * @param {import('./token-sections.mjs').Control | undefined} control Control descriptor.
 * @returns {string} Markdown cell content.
 */
function formatControl(control) {
    if (control === undefined || control.code === undefined) {
        return escapeCell(control?.text ?? '');
    }

    if (control.value === undefined) {
        return codeSpan(control.code);
    }

    return `${codeSpan(control.code)} ${control.separator ?? '='} ${codeSpan(control.value)}`;
}

/**
 * Format a resolved value as a code span, or a dash when a theme lacks it.
 *
 * @param {string | undefined} value Resolved value.
 * @returns {string} Markdown cell content.
 */
function formatValue(value) {
    return value === undefined ? '-' : codeSpan(value);
}

/**
 * Wrap text in a code span, collapsing whitespace and escaping pipes.
 *
 * @param {string} value Text for the span.
 * @returns {string} Markdown code span.
 */
function codeSpan(value) {
    return `\`${escapeCell(value)}\``;
}

/**
 * Escape a value so it cannot end a table cell.
 *
 * @param {string} value Cell text.
 * @returns {string} Text with pipes escaped and whitespace collapsed.
 */
function escapeCell(value) {
    return value.replace(/\s+/g, ' ').trim().replaceAll('|', '\\|');
}
